import math

from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument
from launch.conditions import IfCondition
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node
from launch_ros.parameter_descriptions import ParameterValue


def generate_launch_description():
    return LaunchDescription([
        DeclareLaunchArgument('prediction_model', default_value='dynamic_light', choices=['kinematic', 'dynamic_light', 'dynamic'],
                      description='Planner prediction model; requires planner restart'),
        DeclareLaunchArgument('lookahead_time', default_value='3.0', description='Prediction horizon in seconds'),
        DeclareLaunchArgument('prediction_steps', default_value='10', description='Number of prediction samples'),
        DeclareLaunchArgument('start_costmap_viewer', default_value='true',
                      description='Start the independent GP surface test node'),
        Node(
            package='plan_predictive_cost_map',
            executable='pcm_longitudinal',
            name='pcm_longitudinal',
            output='screen',
            parameters=[{
                'prediction_model': LaunchConfiguration('prediction_model'),
                'lookahead_time': ParameterValue(LaunchConfiguration('lookahead_time'), value_type=float),
                'prediction_steps': ParameterValue(LaunchConfiguration('prediction_steps'), value_type=int),
                'timer_period': 0.05,
                'command_lookahead_time': 0.25,
                'max_longitudinal_acceleration': 5.0,
                'max_lateral_acceleration': 3.0,
                'max_pedestrians': 2,
                'max_vehicles': 2,
                'max_predicted_paths': 2,
                'weight_safety': 0.9,
                'weight_velocity': 0.5,
                'weight_acceleration': 0.0,
                'weight_lateral_acceleration': 0.5,
                'weight_crash': 1.0,
                'pedestrian_cost': 3.0,
                'vehicle_cost': 1.0,
                'ego_lane_cost': -1.0,
                'opposite_lane_cost': -0.1,
                'pedestrian_kernel': [1.0, 3.5, 1.5, 2.0],
                'vehicle_kernel': [math.exp(-1.0), math.exp(1.0), 2.2, 1.0],
                'ego_lane_kernel': [math.exp(value) for value in (-1.0, 1.0, 0.0)],
                'opposite_lane_kernel': [math.exp(-1.0), math.exp(1.0), 2.0],
                'lane_noise_std': 0.001,
                'reference_samples': 96,
                'target_support_points': 128,
                'drivable_support_points': 128,
                'drivable_noise_std': 0.05,
                'pedestrian_noise_base': 0.02,
                'pedestrian_noise_growth': 0.15,
                'vehicle_noise_base': 0.01,
                'vehicle_noise_growth': 0.05,
                'solver_tolerance': 0.001,
                'max_gp_cost': 0.05,
                'vehicle.wheelbase': 2.7,
                'vehicle.mass': 1500.0,
                'vehicle.yaw_inertia': 2500.0,
                'vehicle.front_axle_distance': 1.2,
                'vehicle.front_cornering_stiffness': 80000.0,
                'vehicle.rear_cornering_stiffness': 80000.0,
                'vehicle.air_density': 1.225,
                'vehicle.drag_coefficient': 0.3,
                'vehicle.frontal_area': 2.2,
                'vehicle.rolling_resistance_coefficient': 0.012,
                'vehicle.viscous_resistance': 5.0,
                'vehicle.kinematic_blend_speed': 0.5,
                'vehicle.dynamic_blend_speed': 2.0,
                'vehicle.integration_step': 0.005,
                'vehicle.maximum_acceleration': 9.81,
                'vehicle.maximum_deceleration': 9.81,
                'vehicle.maximum_steering': 0.6,
                'vehicle.lookahead_time': 1.5,
                'vehicle.minimum_lookahead': 2.0,
                'vehicle.control_step': 0.05,
                'dynamic_light.constraint_step': 0.1,
                'vehicle.use_road_gradient': True,
                'vehicle.road_pitch': 0.0,
                'publish_gp_state': ParameterValue(LaunchConfiguration('start_costmap_viewer'), value_type=bool),
                'gp_state_period': 0.1,
                'scenario_worker': True,
            }],
        ),
        Node(
            package='plan_predictive_cost_map',
            executable='pcm_costmap_viewer',
            name='pcm_costmap_viewer',
            output='screen',
            condition=IfCondition(LaunchConfiguration('start_costmap_viewer')),
            parameters=[{
                'resolution': 1.0,
                'forward': 60.0,
                'backward': 5.0,
                'width': 20.0,
                'update_rate': 10.0,
                'prediction_time': 0.5,
                'snap_to_prediction_time': True,
                'height_scale': 1.0,
                'surface_offset': 1.15,
                'opacity': 0.65,
                'stale_timeout': 2.0,
                'max_grid_points': 20000,
            }],
        ),
    ])